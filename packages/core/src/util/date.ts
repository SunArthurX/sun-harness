/** YYYY-MM-DD in the machine's local time zone (user-facing dates; toISOString() would be UTC). */
export function localDate(d = new Date()): string {
  const p = (n: number) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

export function isCalendarDate(value: unknown): value is string {
  if (typeof value !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const date = new Date(`${value}T00:00:00.000Z`);
  return Number.isFinite(date.getTime()) && date.toISOString().slice(0, 10) === value;
}

export function requireCalendarDate(value: unknown): string {
  if (!isCalendarDate(value)) throw new Error('Use a valid calendar date in YYYY-MM-DD format.');
  return value;
}
